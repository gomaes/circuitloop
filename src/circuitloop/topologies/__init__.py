"""Topology library: deterministic design calculators that turn a spec into a complete design.py.

Each topology derives its targets from the spec (output net and voltage, load current, frequency,
gain, ripple, protection), sizes every part with the textbook equations, picks parts from the parts
DB against the derated ratings, and writes the equations into the generated file as comments. The
result is a starting point that is then verified by the normal gates — a topology never decides
pass/fail itself.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from ..partsdb import PartsDB
from ..spec import Spec
from .common import Ctx, bring_out_interfaces
from .writer import DesignWriter, TopologyError

__all__ = ["TOPOLOGIES", "Generated", "Param", "Topology", "TopologyError", "applicable", "generate"]


@dataclass
class Param:
    default: str
    help: str


class Topology:
    name = ""
    summary = ""
    description = ""
    params: dict[str, Param] = {}

    def applicable(self, spec: Spec) -> str | None:
        """None if the topology fits the spec, otherwise the reason it does not."""
        raise NotImplementedError

    def build(self, w: DesignWriter, cx: Ctx) -> str:
        """Place parts and nets; return the one-line title for the docstring."""
        raise NotImplementedError


@dataclass
class Generated:
    topology: str
    text: str
    notes: list[str] = field(default_factory=list)
    params: dict[str, str] = field(default_factory=dict)
    parts: list[tuple[str, str, str | None, str]] = field(default_factory=list)


def _registry() -> dict[str, Topology]:
    from .boost import MC34063Boost
    from .ldo import LinearRegulator
    from .ne555 import NE555Astable
    from .opamp import NonInvertingAmp

    tops = [LinearRegulator(), NE555Astable(), NonInvertingAmp(), MC34063Boost()]
    return {t.name: t for t in tops}


TOPOLOGIES = _registry()


def applicable(spec: Spec) -> list[tuple[str, str | None]]:
    return [(name, t.applicable(spec)) for name, t in TOPOLOGIES.items()]


def generate(
    name: str, spec: Spec, db: PartsDB, params: dict[str, str] | None = None, protect: bool = True
) -> Generated:
    """Size and emit a design. protect=False gives the minimal (Phase 1) variant without the
    protection listed in spec.protection."""
    if name not in TOPOLOGIES:
        raise TopologyError(f"unknown topology '{name}' (available: {', '.join(TOPOLOGIES)})")
    top = TOPOLOGIES[name]
    params = {k: str(v) for k, v in (params or {}).items()}
    unknown = sorted(set(params) - set(top.params))
    if unknown:
        raise TopologyError(
            f"{name}: unknown parameter(s) {', '.join(unknown)} (see `cloop topology show {name}`)"
        )
    why = top.applicable(spec)
    if why:
        raise TopologyError(f"{name} does not fit this spec: {why}")
    cx = Ctx(spec, db, params, protect)
    w = DesignWriter(db)
    title = top.build(w, cx)
    bring_out_interfaces(w, cx)
    shown = {k: params.get(k, p.default) for k, p in top.params.items()}
    doc = [
        title,
        "",
        f"Generated by `cloop topology generate {name}` from spec '{spec.name}'"
        + ("" if protect else " (minimal variant, no protection)")
        + ".",
        "Parameters: " + (", ".join(f"{k}={v}" for k, v in shown.items()) or "(none)"),
        "",
        "Design calculations:",
    ] + [f"  {n}" for n in cx.notes]
    return Generated(
        name,
        w.render("\n".join(doc)),
        list(cx.notes),
        shown,
        [(p.ref, p.key, p.value, p.comment) for p in w.parts],
    )
